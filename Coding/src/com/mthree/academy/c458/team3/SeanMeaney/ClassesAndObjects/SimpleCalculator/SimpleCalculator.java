package com.mthree.academy.c458.team3.SeanMeaney.ClassesAndObjects.SimpleCalculator;

public class SimpleCalculator {

    static double add (double[] in) {
        return in[0]+in[1];
    }

    static double subtract (double[] in) {
        return in[0]-in[1];
    }

    static double multiply (double[] in) {
        return in[0]*in[1];
    }

    static double divide (double[] in) {
        return in[0]/in[1];
    }

}
